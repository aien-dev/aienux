#!/bin/sh
# scripts/fetch_gpu_ucode.sh -- Fetch AMD polaris11 firmware blobs from linux-firmware
# and verify SHA-256 before embedding.  Never commit the blobs.
# Run from the repo root: sh scripts/fetch_gpu_ucode.sh
# Produces: target/native-kernel/gpu_ucode.inc (C arrays for amd_ucode.c)
# AMD firmware is redistributable under AMD's license; see THIRD_PARTY_NOTICES.

set -e

# Work from the repo root whatever the caller's directory (the .inc lands in $REPO/target).
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

OUT=target/native-kernel
mkdir -p "$OUT"

LINUX_FW_BASE="https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/amdgpu"

# Pinned SHA-256 hashes and the upstream commit they were taken from.
# Source: scripts/gpu_ucode_sha256.txt
. scripts/gpu_ucode_sha256.txt

fetch_blob() {
    local name="$1" sha="$2"
    local path="$OUT/$name"
    if [ -f "$path" ]; then
        echo "  $name: already present, checking SHA256..."
    else
        echo "  $name: fetching at $LINUX_FW_COMMIT..."
        curl -fsSL "$LINUX_FW_BASE/$name?id=$LINUX_FW_COMMIT" -o "$path"
    fi
    local actual
    actual=$(sha256sum "$path" | awk '{print $1}')
    if [ "$actual" != "$sha" ]; then
        echo "  ERROR: $name SHA256 mismatch (expected $sha got $actual)" >&2
        rm -f "$path"
        exit 1
    fi
    echo "  $name: OK ($sha)"
}

echo "Fetching polaris11 firmware blobs..."
fetch_blob polaris11_pfp.bin  "$SHA_PFP"
fetch_blob polaris11_me.bin   "$SHA_ME"
fetch_blob polaris11_ce.bin   "$SHA_CE"
fetch_blob polaris11_mec.bin  "$SHA_MEC"
fetch_blob polaris11_mec2.bin "$SHA_MEC2"
fetch_blob polaris11_rlc.bin  "$SHA_RLC"
fetch_blob polaris11_sdma.bin "$SHA_SDMA"
fetch_blob polaris11_sdma1.bin "$SHA_SDMA1"
fetch_blob polaris11_smc.bin "$SHA_SMC"

echo "Generating $OUT/gpu_ucode.inc..."
cat > "$OUT/gpu_ucode.inc" << 'HEADER'
/* target/native-kernel/gpu_ucode.inc -- auto-generated by scripts/fetch_gpu_ucode.sh
 * Do not commit: blobs are not checked in (see scripts/gpu_ucode_sha256.txt for pins). */
HEADER

embed_blob() {
    local name="$1" varname="$2" sizevar="$3"
    local path="$OUT/$name"
    local size
    size=$(stat -c %s "$path")
    local dwords=$(( size / 4 ))
    printf "static const uint32_t g_%s[] = {\n" "$varname" >> "$OUT/gpu_ucode.inc"
    od -An -tx4 -v "$path" | tr -s ' ' | sed 's/ \([0-9a-f]\{8\}\)/0x\1u,/g' >> "$OUT/gpu_ucode.inc"
    printf "};\n" >> "$OUT/gpu_ucode.inc"
    printf "#define %s %uu\n" "$sizevar" "$dwords" >> "$OUT/gpu_ucode.inc"
    echo "  embedded $name: $dwords dwords"
}

embed_blob polaris11_pfp.bin  pfp_ucode  PFP_UCODE_SIZE
embed_blob polaris11_me.bin   me_ucode   ME_UCODE_SIZE
embed_blob polaris11_ce.bin   ce_ucode   CE_UCODE_SIZE
embed_blob polaris11_mec.bin  mec_ucode  MEC_UCODE_SIZE
embed_blob polaris11_mec2.bin mec2_ucode MEC2_UCODE_SIZE
embed_blob polaris11_rlc.bin  rlc_ucode  RLC_UCODE_SIZE

echo "gpu_ucode.inc ready.  Build with: make imac-kernel CK_X86_GPU_UCODE=1"
