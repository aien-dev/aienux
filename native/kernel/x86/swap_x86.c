/* swap_x86.c -- AIENOS-KERNEL-0 live kernel swap (LAB BUILD ONLY: CK_X86_REPORT=1
 * compiles the receiver in; a default image gets the stubs at the bottom).
 *
 * A swap takes a signed slot object (one 4096-byte manifest unit + the raw kernel
 * PE, the format NETLDR.EFI and the slot loader use) and, if it verifies, quiesces
 * the devices and jumps into the new kernel through the trampoline (swap_tramp.S).
 *
 *   1. VERIFY: ck_slot_verify (boot/slot_select.c) -- the same function NETLDR.EFI
 *      calls (boot/net_loader.c:578) -- against the same owner key table
 *      (ck_slot_loader_keys, generated by ck_slot_tool keys-c from CK_SLOT_KEYS or
 *      CK_TEST_SLOT_KEY=1). Checks: manifest structure, signer_id names a trusted
 *      key, the Ed25519 signature over the 448 signed bytes, the image SHA-512.
 *      This file keeps no copy of that logic.
 *   2. PLACE: the firmware loaded this kernel at hand->image_base (a relocated PE);
 *      the new kernel is linked at ImageBase 0. Its base relocations (DIR64) are
 *      applied to the staged copy for the running base, and its sections are laid
 *      out from that base. A new image whose extent is larger than the running
 *      image is refused: it would overwrite memory past the kernel.
 *   3. QUIESCE: APs to their HLT loop, xHCI, tg3, HDA stopped, panel off.
 *   4. JUMP: the trampoline page is opened writable and executable (lab only, after
 *      the verify), the trampoline copies the new sections into place and calls the
 *      new entry with a rebuilt CHANDOF3 handoff.
 *
 * IMAGE SOURCES, as built in this branch:
 *   - CK_X86_SWAP_TEST_DISK (QEMU test only): the slot object is read raw from
 *     LBA 2048 of SATA disk index 2 (the test's third disk).
 *   - UDP port 47034: NOT BUILT. There is no receiver, so a running iMac cannot
 *     take a kernel over the network yet.
 *
 * Honest limits: if tramp_pa is zero (no free page below 1 MiB) the swap is
 * refused. Only DIR64 base relocations are handled; any other fix-up type refuses
 * the image. QEMU runs exercise the verify, place and jump path only; nothing here
 * is tested on the iMac. */
